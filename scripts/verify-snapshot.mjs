#!/usr/bin/env node
// verify-snapshot.mjs — end-to-end verification of the R2 website-snapshot chain
// against the PRODUCTION deployment (https://tagnest.pages.dev).
//
// Flow:
//   1. Register a throwaway user.
//   2. Create a bookmark (also kicks off best-effort auto-snapshot via waitUntil,
//      observed afterwards but not required).
//   3. Call POST /api/bookmarks/:id/snapshot — the synchronous manual path that
//      exercises: auth → ownership → third-party screenshot API → R2 put →
//      snapshot_key update.
//   4. Reload the bookmark and assert snapshotKey was persisted.
//   5. GET /api/snapshots/{key} and assert we receive an image (not a JSON error).
//
// Exit codes: 0 = full chain OK, 1 = any step failed.
//
// Usage (from repo root):
//   node scripts/verify-snapshot.mjs [--base=https://tagnest.pages.dev] [--target=<url>]
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

const arg = (name, fallback) => {
  const hit = process.argv.slice(2).find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
};

async function main() {
  const base = (arg('base', 'https://tagnest.pages.dev') || '').replace(/\/$/, '');
  const target = arg('target', 'https://example.com');
  const email = `snapcheck-${Date.now()}@example.com`;
  const password = 'correct-horse-battery';

  // Perform an HTTP request with curl and return { exit, status, body }.
  // `-w \n%{http_code}` appends the status code on its own trailing line; we
  // split it off, keeping the (possibly binary) body separate.
  function curl(method, url, { body: reqBody, auth, timeout = 60 } = {}) {
    const args = [
      '-s', '--noproxy', '*', '--max-time', String(timeout),
      ...(reqBody ? ['-H', 'Content-Type: application/json', '-d', reqBody] : []),
      ...(auth ? ['-H', `Authorization: Bearer ${auth}`] : []),
      '-w', '\n%{http_code}',
      '-X', method,
      url,
    ];
    const { status, stdout, stderr } = spawnSync('curl', args, { cwd: ROOT, encoding: 'utf8', stdio: 'pipe' });
    if (status !== 0) return { exit: status, body: (stderr || '').trim(), statusCode: 0, json: null };
    const lastNewline = stdout.lastIndexOf('\n');
    const codeStr = stdout.slice(lastNewline + 1).trim();
    const body = lastNewline > 0 ? stdout.slice(0, lastNewline) : stdout;
    const statusCode = /^\d{3}$/.test(codeStr) ? Number(codeStr) : 0;
    let json = null;
    try { json = JSON.parse(body); } catch { /* not JSON (e.g. binary image) */ }
    return { exit: status, body, statusCode, json };
  }

  console.log(`\nBase:   ${base}`);
  console.log(`Target: ${target}`);
  console.log(`User:   ${email}\n`);

  // 1. health
  const h = curl('GET', `${base}/api/health?_cb=${Date.now()}`);
  if (h.json?.status !== 'ok') {
    console.error(`❌ health: expected ok, got HTTP ${h.statusCode} ${h.body.slice(0, 200)}`);
    process.exit(1);
  }
  console.log('✅ 1. health ok');

  // 2. register
  const reg = curl('POST', `${base}/api/auth/register`, {
    body: JSON.stringify({ email, password, displayName: '快照自检' }),
    timeout: 30,
  });
  const token = reg.json?.accessToken || '';
  if (!token) {
    console.error(`❌ register: no accessToken — HTTP ${reg.statusCode} ${reg.body.slice(0, 300)}`);
    process.exit(1);
  }
  console.log('✅ 2. register ok');

  // 3. create bookmark
  const crt = curl('POST', `${base}/api/bookmarks`, {
    body: JSON.stringify({ url: target, title: `Snapshot check ${Date.now()}`, description: 'generated by verify-snapshot.mjs' }),
    auth: token,
    timeout: 30,
  });
  const bookmarkId = crt.json?.id || '';
  if (!bookmarkId) {
    console.error(`❌ create bookmark: no id — HTTP ${crt.statusCode} ${crt.body.slice(0, 300)}`);
    process.exit(1);
  }
  console.log(`✅ 3. created bookmark ${bookmarkId.slice(0, 8)}`);

  // 4. manual snapshot (the synchronous end-to-end path we're validating)
  const snap = curl('POST', `${base}/api/bookmarks/${bookmarkId}/snapshot`, { auth: token, timeout: 90 });
  const sv = snap.json;
  if (snap.statusCode !== 200 || !sv?.snapshotKey || !sv?.url) {
    console.error(`\n❌ manual snapshot: HTTP ${snap.statusCode}`);
    console.error(`   ${snap.body.slice(0, 400)}`);
    if (sv?.errorName || sv?.code || sv?.message) {
      console.error(`   ↳ ${sv.errorName || sv.code}: ${sv.message || ''}`);
    }
    console.error('\n   If this is `snapshot_not_configured`, SNAPSHOT_API_URL is not visible to the deployed Functions.');
    process.exit(1);
  }
  console.log(`✅ 4. manual snapshot: ${sv.snapshotKey}`);

  // 5. reload and confirm snapshot_key persisted on the row
  const list = curl('GET', `${base}/api/bookmarks?scope=all`, { auth: token, timeout: 30 });
  const found = (list.json?.items || []).find((b) => b.id === bookmarkId);
  if (!found || found.snapshotKey !== sv.snapshotKey) {
    console.error(`❌ persist: snapshotKey mismatch. service=${sv.snapshotKey} row=${found?.snapshotKey}`);
    process.exit(1);
  }
  console.log('✅ 5. snapshot_key persisted on the bookmark row');

  // 6. serve the first-party image and confirm it is an image (not a JSON error)
  const img = curl('GET', `${base}${sv.url}`, { timeout: 30 });
  const isJsonError = /^\s*[\[{]/.test(img.body) && (img.body.includes('"error"') || img.body.includes('"code"') || img.body.includes('"message"'));
  if (img.statusCode !== 200 || isJsonError) {
    console.error(`❌ serve image: HTTP ${img.statusCode} ${img.body.slice(0, 200)}`);
    process.exit(1);
  }
  const magic = img.body.slice(0, 4).replace(/[^\x20-\x7e]/g, '.');
  console.log(`✅ 6. GET ${sv.url} → HTTP ${img.statusCode}, ${img.body.length} bytes (magic "${magic}")`);

  console.log('\n🎉 Full R2 snapshot chain verified.');
  console.log(`   Snapshot key: ${sv.snapshotKey}`);
  console.log(`   Serve URL   : ${base}${sv.url}`);
  process.exit(0);
}

main().catch((e) => {
  console.error('❌ unexpected error:', e);
  process.exit(1);
});
